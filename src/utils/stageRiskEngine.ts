/**
 * BhoomiAlert AI — Stage-Wise Delay Risk Prediction Engine
 *
 * ARCHITECTURE:
 * Project Data
 *      ↓
 * Data Validation (Check presence of stage-specific verified fields)
 *      ↓
 * Stage Feature Preparation (Isolate stage features without leakage)
 *      ↓
 * Stage Prediction (Planning / Land Acquisition / Compensation)
 *      ↓
 * SHAP Explanation (Per-stage factor importance breakdown)
 *      ↓
 * Rule-Based Next Actions (Stage-targeted recommendations)
 *
 * CRITICAL DATA INTEGRITY RULES:
 * 1. Missing stage fields (e.g. PPPIN live source) MUST result in 'NOT ASSESSED' and delayProbability = null.
 * 2. Never convert missing values or nulls to 0 or 0%.
 * 3. Never use overall project delay as land-acquisition delay.
 * 4. Overall coverage is 'INCOMPLETE' if any stage lacks sufficient data; 'NOT ASSESSED' is NEVER treated as LOW risk.
 * 5. SHAP is explanation-only, never a predictor.
 * 6. Recommendations are generated by rule-based logic based on active stage factors.
 */

import {
  StageRiskAssessment,
  ProjectStageRiskResponse,
  ShapContribution,
} from '../types';

/**
 * Parses date string in common Indian / international formats safely:
 * DD-MM-YYYY, DD/MM/YYYY, YYYY-MM-DD
 */
function parseDateSafe(rawDate?: string | number | Date | null): Date | null {
  if (!rawDate) return null;
  if (rawDate instanceof Date && !isNaN(rawDate.getTime())) return rawDate;
  if (typeof rawDate === 'number') {
    const d = new Date(rawDate);
    return isNaN(d.getTime()) ? null : d;
  }

  const str = String(rawDate).trim();
  if (!str) return null;

  const dmyMatch = str.match(/^(\d{1,2})[-/](\d{1,2})[-/](\d{4})$/);
  if (dmyMatch) {
    const day = parseInt(dmyMatch[1], 10);
    const month = parseInt(dmyMatch[2], 10) - 1;
    const year = parseInt(dmyMatch[3], 10);
    const d = new Date(year, month, day);
    return isNaN(d.getTime()) ? null : d;
  }

  const ymdMatch = str.match(/^(\d{4})[-/](\d{1,2})[-/](\d{1,2})$/);
  if (ymdMatch) {
    const year = parseInt(ymdMatch[1], 10);
    const month = parseInt(ymdMatch[2], 10) - 1;
    const day = parseInt(ymdMatch[3], 10);
    const d = new Date(year, month, day);
    return isNaN(d.getTime()) ? null : d;
  }

  const standard = new Date(str);
  return isNaN(standard.getTime()) ? null : standard;
}

// -----------------------------------------------------------------------------
// STAGE 1 — PLANNING STAGE PREDICTION
// -----------------------------------------------------------------------------
export function evaluatePlanningStage(project: Record<string, any>): StageRiskAssessment {
  const availableFields: string[] = [];
  const missingFields: string[] = [];

  // 1. Feature Collection (ONLY verified planning fields)
  const sector = project.sector || project.subSector || project.projectType;
  if (sector) availableFields.push('sector');
  else missingFields.push('sector');

  const cost = Number(project.estimatedCostCr ?? project.totalProjectCost ?? project.cost);
  const hasCost = !isNaN(cost) && cost > 0;
  if (hasCost) availableFields.push('estimatedCostCr');
  else missingFields.push('estimatedCostCr');

  const location = project.district || project.taluk || project.village || project.locationName;
  if (location) availableFields.push('location');
  else missingFields.push('location');

  const awardDate = parseDateSafe(project.awardDate || project.dateOfAward || project.sanctionedDate);
  const plannedCompletion = parseDateSafe(project.plannedCompletion || project.expectedCompletion);
  if (awardDate || plannedCompletion) availableFields.push('sanctionedDuration');
  else missingFields.push('sanctionedDuration');

  const status = String(project.status || project.currentStage || '').trim();
  if (status) availableFields.push('projectStatus');

  const rawApproval = project.approvalProgress ?? project['Approval Progress'];
  const hasExplicitApproval = rawApproval !== undefined && rawApproval !== null && !isNaN(Number(rawApproval));
  if (hasExplicitApproval) availableFields.push('approvalProgress');

  const rawDoc = project.documentationProgress ?? project['Documentation Progress'];
  const hasExplicitDoc = rawDoc !== undefined && rawDoc !== null && !isNaN(Number(rawDoc));
  if (hasExplicitDoc) availableFields.push('documentationProgress');

  const surveyStatus = project.surveyStatus || project.rawRecord?.surveyStatus;
  if (surveyStatus) availableFields.push('surveyStatus');

  // Minimum required planning features
  if (availableFields.length < 2) {
    return {
      stage: 'Planning',
      status: 'INSUFFICIENT_DATA',
      riskLevel: 'NOT ASSESSED',
      delayProbability: null,
      factors: ['Not Assessed — Insufficient Stage Data (Baseline project planning metrics missing)'],
      recommendation: 'Record baseline planning parameters (sanctioned budget, award date, and sector classification).',
      shapContributions: [],
      insufficientDataReason: 'Insufficient planning-stage attributes provided in project record.',
      dataCoverage: { availableFields, missingFields },
    };
  }

  // 2. Feature Scoring & Factor Analysis
  let planningScore = 20; // Baseline low friction
  const factors: string[] = [];
  const shapRaw: { factor: string; points: number; isPositive: boolean; desc: string }[] = [];

  // A. Capital Scale Complexity
  if (hasCost) {
    if (cost >= 1500) {
      planningScore += 26;
      factors.push(`Mega-scale capital outlay (> ₹1,500 Cr: ₹${cost.toLocaleString()} Cr)`);
      shapRaw.push({
        factor: 'Capital Outlay Scale',
        points: 26,
        isPositive: true,
        desc: `High capital outlay (₹${cost.toLocaleString()} Cr) requires extensive inter-departmental fiscal sanctions.`,
      });
    } else if (cost >= 750) {
      planningScore += 16;
      factors.push(`Substantial capital outlay (₹${cost.toLocaleString()} Cr)`);
      shapRaw.push({
        factor: 'Capital Outlay Scale',
        points: 16,
        isPositive: true,
        desc: `Medium-high capital outlay (₹${cost.toLocaleString()} Cr) increases sanction oversight.`,
      });
    } else {
      shapRaw.push({
        factor: 'Capital Outlay Scale',
        points: -6,
        isPositive: false,
        desc: `Moderate project scale (₹${cost.toLocaleString()} Cr) falls under standard departmental sanctions.`,
      });
    }
  }

  // B. Sector Right-of-Way Complexity
  const sectorStr = String(sector || '').toLowerCase();
  if (
    sectorStr.includes('port') ||
    sectorStr.includes('waterway') ||
    sectorStr.includes('expressway') ||
    sectorStr.includes('coastal')
  ) {
    planningScore += 22;
    factors.push(`High corridor complexity sector (${sector})`);
    shapRaw.push({
      factor: 'Sector Alignment Complexity',
      points: 22,
      isPositive: true,
      desc: `Sector (${sector}) involves complex environmental, coastal zone, or multi-modal right-of-way clearances.`,
    });
  } else if (sectorStr.includes('road') || sectorStr.includes('highway') || sectorStr.includes('rail')) {
    planningScore += 14;
    factors.push(`Linear corridor sector (${sector})`);
    shapRaw.push({
      factor: 'Sector Alignment Complexity',
      points: 14,
      isPositive: true,
      desc: `Linear infrastructure alignment requires continuous longitudinal corridor clearances.`,
    });
  } else {
    shapRaw.push({
      factor: 'Sector Alignment Complexity',
      points: -5,
      isPositive: false,
      desc: `Sector (${sector || 'General'}) has localized site footprint with standard statutory clearances.`,
    });
  }

  // C. Sanctioned Duration & Timeline Window
  if (awardDate && plannedCompletion) {
    const durationMonths = (plannedCompletion.getTime() - awardDate.getTime()) / (1000 * 60 * 60 * 24 * 30.4375);
    const now = new Date();
    const elapsedMonths = (now.getTime() - awardDate.getTime()) / (1000 * 60 * 60 * 24 * 30.4375);

    if (durationMonths > 48) {
      planningScore += 15;
      factors.push(`Extended sanctioned execution horizon (${Math.round(durationMonths)} months)`);
      shapRaw.push({
        factor: 'Sanctioned Duration Window',
        points: 15,
        isPositive: true,
        desc: `Multi-year horizon (${Math.round(durationMonths)} months) introduces inflation and alignment risk.`,
      });
    } else if (elapsedMonths > durationMonths && durationMonths > 0) {
      planningScore += 20;
      factors.push('Project execution duration has exceeded original sanctioned completion timeline');
      shapRaw.push({
        factor: 'Sanctioned Duration Window',
        points: 20,
        isPositive: true,
        desc: 'Elapsed duration exceeds initial sanction schedule.',
      });
    } else {
      shapRaw.push({
        factor: 'Sanctioned Duration Window',
        points: -4,
        isPositive: false,
        desc: 'Planned duration within normal operational bandwidth.',
      });
    }
  }

  // D. Statutory Clearance / Approval Status (if present)
  if (hasExplicitApproval) {
    const appr = Number(rawApproval);
    if (appr < 50) {
      planningScore += 18;
      factors.push(`Statutory clearance progress is lagging (${appr}%)`);
      shapRaw.push({
        factor: 'Statutory Approval Progress',
        points: 18,
        isPositive: true,
        desc: `Low statutory approvals (${appr}%) directly constrain pre-construction handoff.`,
      });
    } else if (appr > 80) {
      planningScore -= 10;
      shapRaw.push({
        factor: 'Statutory Approval Progress',
        points: -10,
        isPositive: false,
        desc: `High statutory approvals (${appr}%) accelerates pre-construction milestones.`,
      });
    }
  }

  // E. Survey Status (if present)
  if (surveyStatus) {
    const surveyStr = String(surveyStatus).toLowerCase();
    if (surveyStr.includes('pending') || surveyStr.includes('delayed') || surveyStr.includes('in progress')) {
      planningScore += 12;
      factors.push(`Cadastral field survey status: ${surveyStatus}`);
      shapRaw.push({
        factor: 'Cadastral Survey Readiness',
        points: 12,
        isPositive: true,
        desc: `Unfinished cadastral survey delays boundary demarcation.`,
      });
    } else if (surveyStr.includes('completed') || surveyStr.includes('done')) {
      planningScore -= 8;
      shapRaw.push({
        factor: 'Cadastral Survey Readiness',
        points: -8,
        isPositive: false,
        desc: `Completed cadastral survey provides verified boundary coordinates.`,
      });
    }
  }

  const boundedScore = Math.max(10, Math.min(96, Math.round(planningScore)));
  const riskLevel: 'LOW' | 'MEDIUM' | 'HIGH' =
    boundedScore >= 70 ? 'HIGH' : boundedScore >= 40 ? 'MEDIUM' : 'LOW';

  if (factors.length === 0) {
    factors.push('Standard planning parameters with manageable alignment complexity');
  }

  // Rule-based planning recommendation
  let recommendation = 'Proceed with standard planning oversight and coordinate regular inter-departmental reviews.';
  if (boundedScore >= 70) {
    recommendation =
      'Convene High-Level Empowered Committee (HLEC) to expedite statutory clearances and finalize alignment frozen zones.';
  } else if (boundedScore >= 40) {
    recommendation =
      'Complete pending inter-departmental documentation and finalize joint cadastral verification with Revenue authorities.';
  }

  // SHAP Feature Importance normalization
  const totalAbsolute = shapRaw.reduce((acc, s) => acc + Math.abs(s.points), 0) || 1;
  const shapContributions: ShapContribution[] = shapRaw.map((s) => ({
    factor: s.factor,
    percentage: Math.round((Math.abs(s.points) / totalAbsolute) * boundedScore),
    isPositive: s.isPositive,
    impactCategory: Math.abs(s.points) >= 18 ? 'High' : Math.abs(s.points) >= 10 ? 'Medium' : 'Low',
    description: s.desc,
  }));

  return {
    stage: 'Planning',
    status: 'ASSESSED',
    riskLevel,
    delayProbability: boundedScore,
    factors,
    recommendation,
    shapContributions,
    dataCoverage: { availableFields, missingFields },
  };
}

