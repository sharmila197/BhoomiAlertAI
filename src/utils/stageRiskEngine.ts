// STAGE 2 — LAND ACQUISITION STAGE PREDICTION
// -----------------------------------------------------------------------------
export function evaluateLandAcquisitionStage(project: Record<string, any>): StageRiskAssessment {
  const availableFields: string[] = [];
  const missingFields: string[] = [];

  // 1. Strictly check genuine land-acquisition specific fields
  const rawAcqProg =
    project.acquisitionProgress ??
    project.landAcquisitionProgressPercent ??
    project['Land Acquisition Progress %'] ??
    project['Acquisition Progress'] ??
    project['acquisition_progress'];

  const hasAcqProgress =
    rawAcqProg !== undefined &&
    rawAcqProg !== null &&
    String(rawAcqProg).trim() !== '' &&
    !isNaN(Number(rawAcqProg));

  if (hasAcqProgress) availableFields.push('acquisitionProgress');
  else missingFields.push('acquisitionProgress');

  const rawCourtCases =
    project.courtCases ??
    project.legalDisputes ??
    project['Court Cases'] ??
    project['Legal Disputes'] ??
    project['court_cases'];

  const hasCourtCases =
    rawCourtCases !== undefined &&
    rawCourtCases !== null &&
    String(rawCourtCases).trim() !== '' &&
    !isNaN(Number(rawCourtCases));

  if (hasCourtCases) availableFields.push('courtCases');
  else missingFields.push('courtCases');

  const rrStatus =
    project.rrStatus ??
    project.rrProgress ??
    project['R&R Status'] ??
    project['R&R Progress'] ??
    project['rr_progress'];

  const hasRr = rrStatus !== undefined && rrStatus !== null && String(rrStatus).trim() !== '';
  if (hasRr) availableFields.push('rrStatus');
  else missingFields.push('rrStatus');

  const rawSurveyStatus =
    project.surveyStatus ?? project['Survey Status'] ?? project['survey_status'];
  const hasSurvey =
    rawSurveyStatus !== undefined &&
    rawSurveyStatus !== null &&
    String(rawSurveyStatus).trim() !== '';
  if (hasSurvey) availableFields.push('surveyStatus');

  const laStartDate = parseDateSafe(
    project.landAcquisitionStartDate ||
    project['Land Acquisition Start Date'] ||
    project.laStartDate
  );
  const laPlannedDate = parseDateSafe(
    project.plannedLandAcquisitionCompletionDate ||
    project['Planned LA Completion Date'] ||
    project.laPlannedCompletionDate
  );
  const laActualDate = parseDateSafe(
    project.actualLandAcquisitionCompletionDate ||
    project['Actual LA Completion Date'] ||
    project.laActualCompletionDate
  );

  const hasLaDates = Boolean(laStartDate || (laPlannedDate && laActualDate));
  if (hasLaDates) availableFields.push('landAcquisitionDates');
  else missingFields.push('landAcquisitionDates');

  // CRITICAL INTEGRITY CHECK:
  // If land acquisition fields are not genuinely present in the record (such as PPPIN official records):
  // Return NOT ASSESSED. Do NOT fabricate or default missing to 0.
  if (!hasAcqProgress && !hasCourtCases && !hasRr && !hasLaDates) {
    return {
      stage: 'Land Acquisition',
      status: 'INSUFFICIENT_DATA',
      riskLevel: 'NOT ASSESSED',
      delayProbability: null,
      factors: [
        'Not Assessed — Insufficient Stage Data',
        'Land-specific records (Acquisition %, Court cases, Survey status) are unavailable in the source data.',
      ],
      recommendation:
        'Upload departmental land acquisition survey data (via CSV/Excel) to activate Land Acquisition stage prediction.',
      shapContributions: [],
      insufficientDataReason:
        'Land-acquisition specific metrics are not published in live PPPIN infrastructure records.',
      dataCoverage: { availableFields, missingFields },
    };
  }

  // 2. Compute Land Acquisition Risk when data is genuinely available
  let acqScore = 30;
  const factors: string[] = [];
  const shapRaw: { factor: string; points: number; isPositive: boolean; desc: string }[] = [];

  // A. Acquisition Progress Shortfall
  if (hasAcqProgress) {
    const prog = Number(rawAcqProg);
    const shortfall = 100 - prog;
    if (prog < 40) {
      acqScore += 35;
      factors.push(`Severe land acquisition lag (Only ${prog}% acquired, ${shortfall}% remaining)`);
      shapRaw.push({
        factor: 'Acquisition Progress Deficit',
        points: 35,
        isPositive: true,
        desc: `Physical possession achieved for only ${prog}% of required alignment.`,
      });
    } else if (prog < 70) {
      acqScore += 20;
      factors.push(`Moderate land acquisition progress (${prog}% acquired)`);
      shapRaw.push({
        factor: 'Acquisition Progress Deficit',
        points: 20,
        isPositive: true,
        desc: `Partial land handover at ${prog}%, right-of-way gaps remain unaddressed.`,
      });
    } else if (prog >= 90) {
      acqScore -= 20;
      shapRaw.push({
        factor: 'Acquisition Progress Deficit',
        points: -20,
        isPositive: false,
        desc: `Substantial land possession achieved (${prog}%), near complete handoff.`,
      });
    } else {
      shapRaw.push({
        factor: 'Acquisition Progress Deficit',
        points: 5,
        isPositive: true,
        desc: `Steady acquisition at ${prog}%.`,
      });
    }
  }

  // B. Court Cases & Legal Injunctions
  if (hasCourtCases) {
    const disputes = Number(rawCourtCases);
    if (disputes >= 10) {
      acqScore += 30;
      factors.push(`Critical litigation barrier (${disputes} active court petitions / stay orders)`);
      shapRaw.push({
        factor: 'Legal & Court Petitions',
        points: 30,
        isPositive: true,
        desc: `${disputes} active court petitions pending before Land Acquisition, Rehabilitation & Resettlement Authority.`,
      });
    } else if (disputes >= 4) {
      acqScore += 18;
      factors.push(`Active legal disputes (${disputes} cases)`);
      shapRaw.push({
        factor: 'Legal & Court Petitions',
        points: 18,
        isPositive: true,
        desc: `${disputes} legal disputes requiring revenue arbitration hearings.`,
      });
    } else if (disputes === 0) {
      acqScore -= 10;
      shapRaw.push({
        factor: 'Legal & Court Petitions',
        points: -10,
        isPositive: false,
        desc: 'Zero litigations or stay orders against land acquisition parcels.',
      });
    }
  }

  // C. R&R Progress
  if (hasRr) {
    const rrVal = Number(rrStatus);
    if (!isNaN(rrVal)) {
      if (rrVal < 50) {
        acqScore += 15;
        factors.push(`Rehabilitation & Resettlement (R&R) lagging at ${rrVal}%`);
        shapRaw.push({
          factor: 'R&R Package Progress',
          points: 15,
          isPositive: true,
          desc: `R&R execution at ${rrVal}% delays eviction and resettlement colony handover.`,
        });
      } else if (rrVal >= 80) {
        acqScore -= 10;
        shapRaw.push({
          factor: 'R&R Package Progress',
          points: -10,
          isPositive: false,
          desc: `R&R resettlement colony implementation well-advanced at ${rrVal}%.`,
        });
      }
    } else {
      const rrStr = String(rrStatus).toLowerCase();
      if (rrStr.includes('pending') || rrStr.includes('delayed') || rrStr.includes('disputed')) {
        acqScore += 15;
        factors.push(`R&R status: ${rrStatus}`);
        shapRaw.push({
          factor: 'R&R Package Progress',
          points: 15,
          isPositive: true,
          desc: `R&R package issues noted: ${rrStatus}.`,
        });
      }
    }
  }

  // D. Land-Specific Date Slippage (ONLY from land-specific dates, never overall project delay)
  if (laPlannedDate && laActualDate) {
    const delayMonths = (laActualDate.getTime() - laPlannedDate.getTime()) / (1000 * 60 * 60 * 24 * 30.4375);
    if (delayMonths > 6) {
      acqScore += 20;
      factors.push(`Land acquisition deadline exceeded by ${Math.round(delayMonths)} months`);
      shapRaw.push({
        factor: 'Land Schedule Overrun',
        points: 20,
        isPositive: true,
        desc: `Dedicated land milestone passed target date by ${Math.round(delayMonths)} months.`,
      });
    }
  }

  const boundedScore = Math.max(10, Math.min(98, Math.round(acqScore)));
  const riskLevel: 'LOW' | 'MEDIUM' | 'HIGH' =
    boundedScore >= 70 ? 'HIGH' : boundedScore >= 40 ? 'MEDIUM' : 'LOW';

  let recommendation = 'Continue routine field revenue verification and track monthly boundary markers.';
  if (boundedScore >= 70) {
    recommendation =
      'Convene Special CALA Review under DRO/Collector; fast-track hearings for contested parcels and expedite R&R settlement.';
  } else if (boundedScore >= 40) {
    recommendation =
      'Prioritize revenue village level settlement camps and resolve pending award objections under Section 28.';
  }

  const totalAbsolute = shapRaw.reduce((acc, s) => acc + Math.abs(s.points), 0) || 1;
  const shapContributions: ShapContribution[] = shapRaw.map((s) => ({
    factor: s.factor,
    percentage: Math.round((Math.abs(s.points) / totalAbsolute) * boundedScore),
    isPositive: s.isPositive,
    impactCategory: Math.abs(s.points) >= 20 ? 'High' : Math.abs(s.points) >= 12 ? 'Medium' : 'Low',
    description: s.desc,
  }));

  return {
    stage: 'Land Acquisition',
    status: 'ASSESSED',
    riskLevel,
    delayProbability: boundedScore,
    factors,
    recommendation,
    shapContributions,
    dataCoverage: { availableFields, missingFields },
  };
}

// -----------------------------------------------------------------------------
// STAGE 3 — COMPENSATION STAGE PREDICTION
// -----------------------------------------------------------------------------
export function evaluateCompensationStage(project: Record<string, any>): StageRiskAssessment {
  const availableFields: string[] = [];
  const missingFields: string[] = [];

  // 1. Strictly check compensation-specific verified fields
  const compensationStatus =
    project.compensationStatus ||
    project['Compensation Status'] ||
    project['compensation_status'];

  const hasStatus = compensationStatus && String(compensationStatus).trim() !== '';
  if (hasStatus) availableFields.push('compensationStatus');
  else missingFields.push('compensationStatus');

  const rawPendingDays =
    project.pendingCompensationDays ??
    project['Pending Compensation Days'] ??
    project['pending_compensation_days'];

  const hasPendingDays =
    rawPendingDays !== undefined &&
    rawPendingDays !== null &&
    String(rawPendingDays).trim() !== '' &&
    !isNaN(Number(rawPendingDays));

  if (hasPendingDays) availableFields.push('pendingCompensationDays');
  else missingFields.push('pendingCompensationDays');

  const rawCompProg =
    project.compensationProgress ??
    project['Compensation Progress'] ??
    project['compensation_progress'];

  const hasCompProg =
    rawCompProg !== undefined &&
    rawCompProg !== null &&
    String(rawCompProg).trim() !== '' &&
    !isNaN(Number(rawCompProg));

  if (hasCompProg) availableFields.push('compensationProgress');

  const rawTotalComp = project.compensation ?? project.totalCompensation ?? project['Compensation'];
  const rawCompPaid = project.compensationPaid ?? project['Compensation Paid'];
  const rawCompPending = project.compensationPending ?? project['Compensation Pending'];
  const hasCompFinancials = Boolean(
    (rawTotalComp && !isNaN(Number(rawTotalComp))) ||
    (rawCompPaid && !isNaN(Number(rawCompPaid))) ||
    (rawCompPending && !isNaN(Number(rawCompPending)))
  );

  if (hasCompFinancials) availableFields.push('compensationFinancials');
  else missingFields.push('compensationFinancials');

  // CRITICAL INTEGRITY CHECK:
  // If compensation fields are absent (e.g. PPPIN live source):
  // Return NOT ASSESSED with delayProbability: null. Do NOT show 0%.
  if (!hasStatus && !hasPendingDays && !hasCompProg && !hasCompFinancials) {
    return {
      stage: 'Compensation',
      status: 'INSUFFICIENT_DATA',
      riskLevel: 'NOT ASSESSED',
      delayProbability: null,
      factors: [
        'Not Assessed — Insufficient Stage Data',
        'Compensation status and disbursement records are unavailable in the source data.',
      ],
      recommendation:
        'Upload verified compensation disbursement rolls (PFMS/e-Treasury records) to activate Compensation stage prediction.',
      shapContributions: [],
      insufficientDataReason:
        'Compensation disbursement metrics are not published in live PPPIN infrastructure records.',
      dataCoverage: { availableFields, missingFields },
    };
  }

  // 2. Compute Compensation Risk when data is genuinely present
  let compScore = 25;
  const factors: string[] = [];
  const shapRaw: { factor: string; points: number; isPositive: boolean; desc: string }[] = [];

  // A. Pending Compensation Days
  if (hasPendingDays) {
    const days = Number(rawPendingDays);
    if (days >= 90) {
      compScore += 35;
      factors.push(`Severe disbursement pendency (${days} days average delay)`);
      shapRaw.push({
        factor: 'Disbursement Pendency Period',
        points: 35,
        isPositive: true,
        desc: `Compensation awards overdue by ${days} days, risking landowner litigation.`,
      });
    } else if (days >= 30) {
      compScore += 18;
      factors.push(`Moderate disbursement delay (${days} days pending)`);
      shapRaw.push({
        factor: 'Disbursement Pendency Period',
        points: 18,
        isPositive: true,
        desc: `Awards pending disbursement for ${days} days.`,
      });
    } else if (days <= 14) {
      compScore -= 10;
      shapRaw.push({
        factor: 'Disbursement Pendency Period',
        points: -10,
        isPositive: false,
        desc: `Prompt processing with average pendency under 14 days.`,
      });
    }
  }

  // B. Compensation Disbursement Progress
  let effProg = hasCompProg ? Number(rawCompProg) : null;
  if (effProg === null && rawTotalComp && rawCompPaid && Number(rawTotalComp) > 0) {
    effProg = Math.round((Number(rawCompPaid) / Number(rawTotalComp)) * 100);
  }

  if (effProg !== null) {
    const shortfall = 100 - effProg;
    if (effProg < 45) {
      compScore += 30;
      factors.push(`Major compensation shortfall (Only ${effProg}% disbursed, ${shortfall}% pending)`);
      shapRaw.push({
        factor: 'Disbursement Progress Deficit',
        points: 30,
        isPositive: true,
        desc: `Only ${effProg}% of total compensation award deposited to affected titleholders.`,
      });
    } else if (effProg < 75) {
      compScore += 15;
      factors.push(`Partial compensation disbursement (${effProg}% paid)`);
      shapRaw.push({
        factor: 'Disbursement Progress Deficit',
        points: 15,
        isPositive: true,
        desc: `Compensation progress at ${effProg}%.`,
      });
    } else if (effProg >= 90) {
      compScore -= 18;
      shapRaw.push({
        factor: 'Disbursement Progress Deficit',
        points: -18,
        isPositive: false,
        desc: `Over ${effProg}% compensation successfully disbursed.`,
      });
    }
  }

  // C. Compensation Status string
  if (hasStatus) {
    const statusStr = String(compensationStatus).toLowerCase();
    if (statusStr.includes('disputed') || statusStr.includes('litigation') || statusStr.includes('delayed')) {
      compScore += 20;
      factors.push(`Compensation audit status flagged: ${compensationStatus}`);
      shapRaw.push({
        factor: 'Title Verification Friction',
        points: 20,
        isPositive: true,
        desc: `Title or share verification bottlenecks flagged under status: ${compensationStatus}.`,
      });
    } else if (statusStr.includes('cleared') || statusStr.includes('completed') || statusStr.includes('disbursed')) {
      compScore -= 12;
      shapRaw.push({
        factor: 'Title Verification Friction',
        points: -12,
        isPositive: false,
        desc: 'Compensation disbursement verified without title flags.',
      });
    }
  }

  const boundedScore = Math.max(10, Math.min(96, Math.round(compScore)));
  const riskLevel: 'LOW' | 'MEDIUM' | 'HIGH' =
    boundedScore >= 70 ? 'HIGH' : boundedScore >= 40 ? 'MEDIUM' : 'LOW';

  let recommendation = 'Maintain DBT queue reconciliation and monitor bank confirmation receipts.';
  if (boundedScore >= 70) {
    recommendation =
      'Initiate emergency compensation disbursal camps; escalate treasury sanctions and establish escrow for disputed titles.';
  } else if (boundedScore >= 40) {
    recommendation =
      'Audit pending bank accounts and clear Section 19 award notices for uncollected entitlements.';
  }

  const totalAbsolute = shapRaw.reduce((acc, s) => acc + Math.abs(s.points), 0) || 1;
  const shapContributions: ShapContribution[] = shapRaw.map((s) => ({
    factor: s.factor,
    percentage: Math.round((Math.abs(s.points) / totalAbsolute) * boundedScore),
    isPositive: s.isPositive,
    impactCategory: Math.abs(s.points) >= 20 ? 'High' : Math.abs(s.points) >= 12 ? 'Medium' : 'Low',
    description: s.desc,
  }));

  return {
    stage: 'Compensation',
    status: 'ASSESSED',
    riskLevel,
    delayProbability: boundedScore,
    factors,
    recommendation,
    shapContributions,
    dataCoverage: { availableFields, missingFields },
  };
}

// -----------------------------------------------------------------------------
// OVERALL EVALUATOR
// -----------------------------------------------------------------------------
export function calculateStageWiseRisk(project: Record<string, any>): ProjectStageRiskResponse {
  const projectId = String(project.projectId || project.id || 'LA-UNKNOWN');
  const projectName = String(project.projectName || project.name || `Project ${projectId}`);

  const planning = evaluatePlanningStage(project);
  const landAcquisition = evaluateLandAcquisitionStage(project);
  const compensation = evaluateCompensationStage(project);

  const stages = [planning, landAcquisition, compensation];
  const assessedStages = stages.filter((s) => s.status === 'ASSESSED');
  const assessedCount = assessedStages.length;
  const totalStages = 3;

  const isComplete = assessedCount === totalStages;
  const overallCoverage: 'COMPLETE' | 'INCOMPLETE' = isComplete ? 'COMPLETE' : 'INCOMPLETE';

  let overallDelayProbability: number | null = null;
  let overallRiskLevel: 'LOW' | 'MEDIUM' | 'HIGH' | 'NOT ASSESSED' = 'NOT ASSESSED';

  if (isComplete) {
    // When all 3 stages assessed: Weighted aggregation
    // Planning: 25%, Land Acquisition: 45%, Compensation: 30%
    const pProb = planning.delayProbability ?? 50;
    const laProb = landAcquisition.delayProbability ?? 50;
    const cProb = compensation.delayProbability ?? 50;

    const aggregate = Math.round(0.25 * pProb + 0.45 * laProb + 0.30 * cProb);
    overallDelayProbability = Math.max(10, Math.min(98, aggregate));
    overallRiskLevel =
      overallDelayProbability >= 70 ? 'HIGH' : overallDelayProbability >= 40 ? 'MEDIUM' : 'LOW';
  } else if (assessedCount > 0) {
    // If incomplete, provide average of ASSESSED stages only, but keep overallCoverage = INCOMPLETE
    const sum = assessedStages.reduce((acc, s) => acc + (s.delayProbability || 0), 0);
    overallDelayProbability = Math.round(sum / assessedCount);
    overallRiskLevel =
      overallDelayProbability >= 70 ? 'HIGH' : overallDelayProbability >= 40 ? 'MEDIUM' : 'LOW';
  }

  return {
    projectId,
    projectName,
    overallCoverage,
    assessedCount,
    totalStages,
    overallRiskLevel,
    overallDelayProbability,
    planning,
    landAcquisition,
    compensation,
    timestamp: new Date().toISOString(),
  };
}
